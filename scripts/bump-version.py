#!/usr/bin/env python3
"""Lockstep version sweep for the MADVentures Claude Code Environment.

The package asserts its version in several hand-maintained surfaces plus pinned
literals in build/validation scripts. History shows partial bumps drift
silently (the tripwire test fails *after* the fact); this tool makes the sweep
mechanical:

    python3 scripts/bump-version.py --list           # sweep set + current VERSION
    python3 scripts/bump-version.py X.Y.Z            # dry run: per-file counts
    python3 scripts/bump-version.py X.Y.Z --apply    # write the replacements

Generated files (MANIFEST.json, PACKAGE_CONTENTS.txt, SHA256SUMS.txt,
docs/VALIDATION_REPORT.md) are deliberately NOT swept — regenerate them in the
canonical order afterwards: generate-delivery-index -> generate-manifest ->
quick-validate. CHANGELOG.md is curated by hand.

Occurrences embedded in release-directory names (e.g. "4.4.2-20261003") are
never rewritten; only the bare version literal is replaced.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Hand-maintained files that must carry the current version. Keep this list in
# sync with the release skill's sweep set; the tripwire test covers the core
# identity surfaces.
SWEEP = [
    "VERSION",
    "python-control-plane/pyproject.toml",
    "python-control-plane/src/madclaude/version.py",
    "plugin/madventures-founderos/python-control-plane/src/madclaude/version.py",
    "plugin/madventures-founderos/.claude-plugin/plugin.json",
    "scripts/validate-config.py",
    "scripts/test-python-control-plane.sh",
    "scripts/verify-release.py",
    "scripts/smoke-test-install.sh",
    "scripts/install-python-control-plane.sh",
    "scripts/generate-manifest.py",
    "scripts/create-zip.py",
    "cloud/setup.sh",
    "INSTALL_MAC.command",
    "README.md",
    "START_HERE.md",
    "docs/DEPLOYMENT.md",
    "docs/UPGRADE_FROM_V4.md",
    "python-control-plane/README.md",
    "plugin/madventures-founderos/README.md",
]

GENERATED_HANDLED_BY_REGEN = (
    "MANIFEST.json",
    "PACKAGE_CONTENTS.txt",
    "SHA256SUMS.txt",
    "docs/VALIDATION_REPORT.md",
)


def old_version() -> str:
    return (ROOT / "VERSION").read_text(encoding="utf-8").strip()


def literal_pattern(version: str) -> re.Pattern[str]:
    # Match the bare version literal only: not preceded by a digit/dot, and not
    # followed by a digit or hyphen (which would make it a release-dir name
    # like 4.4.2-20261003).
    return re.compile(r"(?<![\d.])" + re.escape(version) + r"(?![\d-])")


def main() -> int:
    parser = argparse.ArgumentParser(description="Lockstep version sweep.")
    parser.add_argument("version", nargs="?", help="target version, e.g. 4.4.3")
    parser.add_argument("--apply", action="store_true", help="write the replacements")
    parser.add_argument("--dry-run", action="store_true", help="default; accepted for explicitness")
    parser.add_argument("--list", action="store_true", help="print the sweep set and exit")
    parser.add_argument("--allow-missing", action="store_true",
                        help="tolerate listed files that contain no occurrence")
    parser.add_argument("--allow-dirty", action="store_true",
                        help="allow sweeping on top of uncommitted edits")
    args = parser.parse_args()

    current = old_version()

    if args.list:
        print(f"current version: {current}")
        print(f"sweep set ({len(SWEEP)} files):")
        for rel in SWEEP:
            print(f"  {rel}")
        print("generated by regeneration (not swept):")
        for rel in GENERATED_HANDLED_BY_REGEN:
            print(f"  {rel}")
        return 0

    if not args.version:
        parser.print_usage(sys.stderr)
        print("error: target version is required (or pass --list)", file=sys.stderr)
        return 5

    target = args.version.strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+", target):
        print(f"error: target version {target!r} is not X.Y.Z", file=sys.stderr)
        return 5
    if target == current:
        print(f"error: target version equals current version ({current})", file=sys.stderr)
        return 5

    pattern = literal_pattern(current)
    rows: list[tuple[str, int]] = []
    missing: list[str] = []
    for rel in SWEEP:
        path = ROOT / rel
        if not path.is_file():
            print(f"error: sweep file missing: {rel}", file=sys.stderr)
            return 6
        text = path.read_text(encoding="utf-8")
        count = len(pattern.findall(text))
        if count == 0:
            missing.append(rel)
        rows.append((rel, count))

    if missing and not args.allow_missing:
        print(f"error: no occurrence of {current} in: {', '.join(missing)}", file=sys.stderr)
        print("(drift or a wrong sweep set; pass --allow-missing to tolerate)", file=sys.stderr)
        return 6

    total = sum(count for _, count in rows)
    mode = "APPLY" if args.apply else "DRY RUN"
    print(f"{mode} — replacing {current} -> {target}")
    for rel, count in rows:
        marker = "" if count else "  (no occurrence)"
        print(f"  {count:>3} replacement(s)  {rel}{marker}")
    print(f"total: {total} replacement(s) across {len(rows)} files")

    if not args.apply:
        print()
        print("no files written; pass --apply to write the replacements")
        return 0

    dirty = subprocess.run(
        ["git", "-C", str(ROOT), "status", "--porcelain", "--", *SWEEP],
        capture_output=True, text=True,
    )
    if dirty.returncode == 0 and dirty.stdout.strip() and not args.allow_dirty:
        print("error: sweep files have uncommitted changes; commit or discard them first "
              "(or pass --allow-dirty):", file=sys.stderr)
        print(dirty.stdout, file=sys.stderr)
        return 6

    for rel, _ in rows:
        path = ROOT / rel
        text = path.read_text(encoding="utf-8")
        path.write_text(pattern.sub(target, text), encoding="utf-8")

    print()
    print("written. Next:")
    print("  1) update CHANGELOG.md's top section by hand (curated, not swept)")
    print("  2) regenerate: generate-delivery-index -> generate-manifest -> quick-validate")
    print("  3) run the version-consistency tripwire (part of the installed suite)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
